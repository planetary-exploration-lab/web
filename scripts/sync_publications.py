#!/usr/bin/env python3
"""Write the public publication list from the private CV export.

Reads <private>/publications/cv-export/cv-items-latest.yaml (the whole CV) and <private>/publications/select.yaml,
keeps the selected records and the fields the site uses, and writes src/data/publications.yaml.
Lab members are marked (bold) by matching each author against the people the site lists (<private>/people with listing
consent), from any era. The export's trainee_authors (GT advisees only) is used as a cross-check.
Run from web/:  python3 -I scripts/sync_publications.py [--private ../web-private]
"""
from __future__ import annotations

import argparse
import re
import sys
import unicodedata
from pathlib import Path
from urllib.parse import urlparse

import yaml

FIELDS = [
    "id", "type", "subtype", "title", "authors", "author_names", "owner_author", "trainee_authors", "venue",
    "venue_abbrev", "date", "year", "volume", "number", "pages", "publisher", "location", "doi", "pmid", "pmcid",
    "url", "arxiv", "links", "listed",
]
OUT = Path("src/data/publications.yaml")
SIDECARS = Path("src/content/publications")
HEADER = (
    "# Generated by scripts/sync_publications.py. Do not edit by hand: changes are overwritten on the next sync.\n"
    "# Site-only extras (featured order, summary, project links) live in src/content/publications/<id>.yaml.\n"
)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--private", default="../web-private", help="path to the private repository")
    args = ap.parse_args()
    base = Path(args.private) / "publications"
    records = yaml.safe_load((base / "cv-export" / "cv-items-latest.yaml").read_text(encoding="utf-8"))
    sel = yaml.safe_load((base / "select.yaml").read_text(encoding="utf-8"))
    types = set(sel.get("include_types") or [])
    include = set(sel.get("include_ids") or [])
    exclude = set(sel.get("exclude_ids") or [])
    exclude_subtypes = set(sel.get("exclude_subtypes") or [])

    ids = {r["id"] for r in records}
    unknown = sorted((include | exclude) - ids)
    if unknown:
        print(f"sync_publications: select.yaml names ids not in the export: {', '.join(unknown)}", file=sys.stderr)
        return 1

    chosen = [
        r for r in records
        if r["id"] not in exclude and r.get("subtype") not in exclude_subtypes
        and (r["id"] in include or (r["type"] in types and not r.get("unpublished")))
    ]
    # Records tagged with a project in their sidecar (talks, posters, abstracts, theses) are published for project
    # pages only: listed: false keeps them off the Publications page. Exclusions and unpublished records still win.
    tagged = project_tagged()
    unknown_tags = sorted(tagged - ids)
    if unknown_tags:
        print(f"sync_publications: sidecars tag ids not in the export: {', '.join(unknown_tags)}", file=sys.stderr)
        return 1
    have = {r["id"] for r in chosen}
    for r in records:
        if (r["id"] in tagged and r["id"] not in have and r["id"] not in exclude and not r.get("unpublished")
                and r.get("subtype") not in exclude_subtypes):
            chosen.append({**r, "listed": False})
    # Stable order (newest year first, then id) so a re-export only changes lines whose data changed.
    chosen.sort(key=lambda r: (-int(r["year"]), r["id"]))
    # Unpublished work reaches the site only when selected by id, and then as its preprint: no journal is named
    # before acceptance, and the date is the preprint's (from the arXiv id, YYMM.NNNNN).
    for r in chosen:
        if r.get("unpublished"):
            as_preprint(r)
    listed = listed_people(Path(args.private) / "people")
    dropped: set[str] = set()
    added: set[str] = set()
    for r in chosen:
        r["trainee_authors"] = mark_members(r, listed, dropped, added)
    out = [{k: r[k] for k in FIELDS if r.get(k) not in (None, "", [])} for r in chosen]
    OUT.write_text(HEADER + yaml.safe_dump(out, allow_unicode=True, sort_keys=False, width=120), encoding="utf-8")
    counts: dict[str, int] = {}
    for r in out:
        counts[r["type"]] = counts.get(r["type"], 0) + 1
    detail = ", ".join(f"{n} {t}" for t, n in sorted(counts.items()))
    project_only = sum(1 for r in out if r.get("listed") is False)
    print(f"sync_publications: wrote {len(out)} of {len(records)} records to {OUT} ({detail}; {project_only} for project pages only)")
    if dropped:
        print(f"sync_publications: not bolded (CV trainees not listed on the site): {', '.join(sorted(dropped))}")
    if added:
        print(f"sync_publications: bolded but not CV trainees (check these are the listed person): {', '.join(sorted(added))}")
    return 0


def project_tagged() -> set[str]:
    """Ids whose sidecar (src/content/publications/<id>.yaml) lists at least one project."""
    out = set()
    for f in sorted(SIDECARS.glob("*.y*ml")):
        d = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        if d.get("projects"):
            out.add(f.stem)
    return out


def as_preprint(r: dict) -> None:
    arxiv = r.get("arxiv")
    if not arxiv:
        sys.exit(f"sync_publications: {r['id']} is unpublished and has no arXiv id; select only records with a preprint")
    r["type"], r["venue"] = "preprint", "arXiv"
    for k in ("venue_abbrev", "volume", "number", "pages", "publisher", "doi", "pmid", "pmcid"):
        r.pop(k, None)
    if re.match(r"^\d{4}\.\d{4,5}", str(arxiv)):
        r["date"], r["year"] = f"20{arxiv[:2]}-{arxiv[2:4]}", int(f"20{arxiv[:2]}")
    r["links"] = [l for l in r.get("links") or [] if not (l.get("kind") == "preprint" and urlparse(l.get("url", "")).hostname in ("arxiv.org", "www.arxiv.org"))]


def norm(s: str) -> str:
    """Lowercase letters only, accents removed: "Ramírez-Colón" and "Ramírez Colón" both become "ramirezcolon"."""
    s = unicodedata.normalize("NFKD", s)
    return "".join(c for c in s if c.isalpha() and not unicodedata.combining(c)).lower()


def listed_people(people_dir: Path) -> list[tuple[str, str]]:
    """(normalized full name, first initial) for everyone the site lists, i.e. with listing consent."""
    out = []
    for f in sorted(people_dir.glob("*.yaml")):
        if f.name.startswith("_"):
            continue
        p = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        if not (p.get("consent", {}).get("listing", {}) or {}).get("granted"):
            continue
        name = re.sub(r'"[^"]*"', " ", p.get("name", ""))  # drop a quoted nickname: Ziqin "Grace" Ni
        if name.split():
            out.append((norm(name), norm(name.split()[0])[:1]))
    return out


def author_parts(r: dict, i: int) -> tuple[str, str]:
    """(family name, first initial) of author i, from author_names or else the display string "J. L. Ramírez-Colón"."""
    names = r.get("author_names") or []
    if i < len(names) and names[i].get("family"):
        n = names[i]
        return n["family"], (n.get("initials") or n.get("given") or "")[:1]
    tokens = r["authors"][i].split()
    return (" ".join(t for t in tokens if not t.endswith(".")) or tokens[-1]), tokens[0][:1]


def mark_members(r: dict, listed: list[tuple[str, str]], dropped: set[str], added: set[str]) -> list[int]:
    """Indices of authors who match a person listed on the site (family name + first initial), the owner excepted.
    Listing on the site is the permission to bold. Differences from the export's trainee_authors are reported."""
    flagged = set(r.get("trainee_authors") or [])
    keep = []
    for i, name in enumerate(r["authors"]):
        if i == r.get("owner_author"):
            continue
        family, initial = author_parts(r, i)
        if family and initial and any(full.endswith(norm(family)) and first == norm(initial)[:1] for full, first in listed):
            keep.append(i)
            if i not in flagged:
                added.add(name)
        elif i in flagged:
            dropped.add(name)
    return keep


if __name__ == "__main__":
    sys.exit(main())
